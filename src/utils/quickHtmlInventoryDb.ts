export const ALL_QUICKHTML_INVENTORY_ITEMS: QuickHtmlInventoryItem[] = (() => {
  const seen = new Set<string>();
  const combined: QuickHtmlInventoryItem[] = [];
  for (const item of [
    ...QUICKHTML_INVENTORY_ITEMS,
    ...QUICKHTML_EXTRA_CATALOG,
    ...QUICKHTML_ATOMIC_AND_JS_CATALOG,
  ]) {
    if (!seen.has(item.id)) {
      seen.add(item.id);
      combined.push(item);
    }
  }
  return combined;
})();

/**
 * Restituisce una mappa { [id]: RegistryComponentDef } pronta per il compilatore QuickHTML
 */
export function buildQuickHtmlRegistryMap(
  customItems: Record<string, RegistryComponentDef> = {}
): Record<string, RegistryComponentDef> {
  const map: Record<string, RegistryComponentDef> = { ...INITIAL_APPFORGE_REGISTRY };
  ALL_QUICKHTML_INVENTORY_ITEMS.forEach((item) => {
    map[item.id] = item;
  });
  Object.entries(customItems).forEach(([k, v]) => {
    map[k] = v;
  });
  return map;
}

